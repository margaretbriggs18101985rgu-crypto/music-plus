//! Run npm run build:theme after changing these two page themes.
const fs = require('fs')
const path = require('path')
const { createThemeColors } = require('./utils')
const defaultThemes = [
  { id: 'mineradio', name: '黑胶深色', isDark: true, primary: 'rgb(235, 235, 240)', font: 'rgb(243, 243, 245)', background: '#0D0D12' },
  { id: 'white', name: '白色', isDark: false, primary: 'rgb(40, 40, 48)', font: 'rgb(27, 27, 32)', background: '#FAFAFC' },
]
const themes = defaultThemes.map(({ primary, font, background, ...info }) => ({
  ...info,
  isCustom: false,
  config: {
    themeColors: createThemeColors(primary, font, info.isDark),
    extInfo: {
      'c-app-background': background,
      'c-main-background': background,
      'bg-image': '',
      'bg-image-position': 'center',
      'bg-image-size': 'cover',
      'c-badge-primary': 'var(c-primary)',
      'c-badge-secondary': info.isDark ? '#A4A4AC' : '#72727A',
      'c-badge-tertiary': info.isDark ? '#929298' : '#72727A',
    },
  },
}))
fs.writeFileSync(path.join(__dirname, 'themes.ts'), `/* eslint-disable */\n//! Generated by createThemes.js\n\nexport default ${JSON.stringify(themes, null, 2)} as const\n`)
